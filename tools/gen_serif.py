"""CONDUCTOR's serif fonts: DejaVu Serif Bold rendered at three sizes (and Bold Italic at two, for the dynamics) into firmware/gen/serif_font.h, in the
felucca_font_t format gfx.c draws (4-bit alpha, proportional). DejaVu fonts: Bitstream Vera licence (free to embed
and redistribute, see firmware/gen/DEJAVU-LICENSE.txt). The font file comes from matplotlib (pip install matplotlib)
or --ttf.
    python tools/gen_serif.py [--ttf DejaVuSerif-Bold.ttf]"""
import argparse
import os
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

PAD = 1
SIZES = {"SERIF_S": 10, "SERIF_M": 14, "SERIF_L": 26}   # pixel sizes (em)
ITALIC = {"ITAL_M": 15, "ITAL_L": 34}           # bold italic: the dynamics (pp p mp mf f ff), as printed music has them


def default_ttf():
    import matplotlib
    return Path(matplotlib.__file__).parent / "mpl-data" / "fonts" / "ttf" / "DejaVuSerif-Bold.ttf"


def render(ttf, name, size):
    f = ImageFont.truetype(str(ttf), size)
    asc, desc = f.getmetrics()
    h = asc + desc
    adv, bw, off, data = [], [], [], []
    for ch in range(32, 127):
        a = int(round(f.getlength(chr(ch))))
        x0, _, x1, _ = f.getbbox(chr(ch))
        w = max(a, x1) + 2 * PAD
        img = Image.new("L", (w, h), 0)
        ImageDraw.Draw(img).text((PAD, 0), chr(ch), font=f, fill=255)
        bpr = (w + 1) // 2
        off.append(len(data))
        px = img.load()
        for y in range(h):
            row = [px[x, y] * 15 // 255 for x in range(w)] + [0]
            data += [(row[2 * i] << 4) | row[2 * i + 1] for i in range(bpr)]
        adv.append(a)
        bw.append(w)
    out = [f"static const uint8_t {name}_ADV[95] = {{{', '.join(map(str, adv))}}};",
           f"static const uint8_t {name}_BW[95] = {{{', '.join(map(str, bw))}}};",
           f"static const uint16_t {name}_OFF[95] = {{{', '.join(map(str, off))}}};",
           f"static const uint8_t {name}_DATA[{len(data)}] = {{"]
    for i in range(0, len(data), 24):
        out.append("    " + ", ".join(map(str, data[i:i + 24])) + ",")
    out.append("};")
    out.append(f"static const felucca_font_t {name} = {{ {h}, {PAD}, 32, 126, {name}_ADV, {name}_BW, {name}_OFF, {name}_DATA }};")
    return "\n".join(out)


def clef():
    """a treble clef, drawn with curves at 8x and scaled down to 12 x 24 (4-bit alpha, a byte a pixel)"""
    import math
    S = 8
    im = Image.new("L", (12 * S, 24 * S), 0)
    d = ImageDraw.Draw(im)
    lw = int(1.6 * S)

    def spiral(t):
        a = 0.6 * S + 4.2 * S * t
        ang = math.pi * 0.5 + t * 2.6 * math.pi
        return (6 * S + a * math.cos(ang), 15.5 * S + a * math.sin(ang))
    d.line([spiral(i / 200) for i in range(201)], fill=255, width=lw, joint="curve")
    x0, y0 = spiral(1)
    d.line([(x0, y0), (9.5 * S, 12 * S), (9.2 * S, 8 * S), (7.5 * S, 4.5 * S), (7.2 * S, 1.2 * S), (5.0 * S, 3 * S),
            (4.8 * S, 7 * S), (6.6 * S, 12 * S), (7.2 * S, 19 * S), (6.6 * S, 22 * S), (4.6 * S, 22.4 * S)],
           fill=255, width=lw, joint="curve")
    d.ellipse([3.0 * S, 20.0 * S, 5.4 * S, 22.6 * S], fill=255)
    sm = im.resize((12, 24), Image.LANCZOS).load()
    vals = [sm[x, y] * 15 // 255 for y in range(24) for x in range(12)]
    return "static const uint8_t CLEF[24 * 12] = {" + ", ".join(map(str, vals)) + "};   /* 12 x 24, alpha 0..15 */"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--ttf", type=Path, default=None)
    a = ap.parse_args()
    ttf = a.ttf or default_ttf()
    root = Path(__file__).resolve().parent.parent
    parts = ["/* generated by tools/gen_serif.py from DejaVu Serif Bold (Bitstream Vera licence: DEJAVU-LICENSE.txt) */",
             "#pragma once"]
    for name, size in SIZES.items():
        parts.append(render(ttf, name, size))
    ital = ttf.with_name("DejaVuSerif-BoldItalic.ttf")
    for name, size in ITALIC.items():
        parts.append(render(ital, name, size))
    parts.append(clef())
    (root / "firmware" / "gen" / "serif_font.h").write_text("\n".join(parts) + "\n")
    print("firmware/gen/serif_font.h")


if __name__ == "__main__":
    main()
